WITH REPEATED_2015_TIV AS (
    SELECT 
        DF1.TIV_2015
    FROM INSURANCE AS DF1
    GROUP BY DF1.TIV_2015
    HAVING COUNT(*) > 1
),
UNIQUE_CITY AS (
    SELECT 
        DF1.PID
    FROM INSURANCE AS DF1
    GROUP BY LAT, LON
    HAVING COUNT(*) = 1
)

SELECT
    ROUND(SUM(TIV_2016), 2) AS tiv_2016
FROM INSURANCE AS  I
WHERE I.TIV_2015 IN (SELECT TIV_2015 FROM REPEATED_2015_TIV)
    AND I.PID IN (SELECT PID FROM UNIQUE_CITY)